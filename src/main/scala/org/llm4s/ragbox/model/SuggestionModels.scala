  avgChunksRetrieved: Double,
  avgChunksUsed: Double,
  avgRating: Option[Double],
  ratedQueryCount: Int,
  zeroResultQueries: Int,
  p95LatencyMs: Int,
  collectionMetrics: Seq[CollectionMetrics]
